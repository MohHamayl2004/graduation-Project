import test from "node:test";
import assert from "node:assert/strict";
import { randomBytes, randomUUID } from "node:crypto";
import request from "supertest";
import { createApp } from "../app.js";
import User from "../models/User.js";
import StudyPlan from "../models/StudyPlan.js";
import LearningAssessment from "../models/LearningAssessment.js";
import { signToken } from "../services/tokenService.js";
import { connectTestDatabase, clearTestCollections, disconnectTestDatabase } from "./helpers/testDatabase.js";
const daily = { type: "daily", goal: "regular", periodStart: "2026-10-18", lessonIds: ["math-u1-l1", "math-u1-l2"], availability: [{ date: "2026-10-18", start: "16:00", end: "18:00" }] };
test("database generation, snapshots, old plans, replacement, retries, editing and weekly linkage are owner scoped", { skip: !process.env.MONGO_URI_TEST, timeout: 60000 }, async () => {
  process.env.JWT_SECRET ||= randomBytes(48).toString("hex");
  try {
    await connectTestDatabase(); await Promise.all([User.init(), StudyPlan.init(), LearningAssessment.init()]); await clearTestCollections();
    const owner = await User.create({ fullName: "اختبار خطة", email: "schedule@example.invalid", passwordHash: "unused" });
    const other = await User.create({ fullName: "طالب آخر", email: "schedule-other@example.invalid", passwordHash: "unused" });
    await LearningAssessment.create({ owner: owner._id, version: "test-vark", completedAt: new Date(), scores: { V: 1, A: 2, R: 3, K: 9 } });
    const app = createApp(), token = await signToken(owner._id), otherToken = await signToken(other._id);
    const asOwner = (req) => req.auth(token, { type: "bearer" });
    const key = randomUUID();
    const create = () => asOwner(request(app).post("/api/study-plan/plans")).send({ ...daily, creationKey: key });
    const created = await create(); assert.equal(created.status, 201);
    const id = created.body.plan._id;
    assert.equal((await create()).body.plan._id, id); assert.equal(await StudyPlan.countDocuments({ owner: owner._id }), 1);
    const generate = (body = {}) => asOwner(request(app).post(`/api/study-plan/plans/${id}/generate`)).send(body);
    assert.equal((await request(app).post(`/api/study-plan/plans/${id}/generate`)).status, 401);
    assert.equal((await request(app).post(`/api/study-plan/plans/${id}/generate`).auth(otherToken, { type: "bearer" }).send({})).status, 404);
    const result = await generate({ requestKey: "first", scores: { V: 999 }, sessions: [{ minutes: 1 }] });
    assert.equal(result.status, 200); assert.equal(result.body.plan.generated.assessment.scores.K, 9);
    assert.equal(result.body.plan.generated.assessment.scores.V, 1);
    assert.equal(result.body.plan.generated.remainingStudyMinutes, 0);
    const loaded = (await asOwner(request(app).get("/api/study-plan/plans"))).body.plans[0];
    assert.deepEqual(loaded.generated, result.body.plan.generated);
    const revision = loaded.generationRevision;
    const repeat = await generate({ requestKey: "first" }); assert.equal(repeat.body.plan.generationRevision, revision);
    const update = await asOwner(request(app).put(`/api/study-plan/plans/${id}`)).send({ ...daily, availability: [{ date: "2026-10-18", start: "16:00", end: "16:15" }], expectedRevision: revision });
    assert.equal(update.status, 200); assert.equal(update.body.plan.generatedStale, true);
    assert.deepEqual(update.body.plan.generated, loaded.generated);
    assert.equal((await generate({})).status, 409);
    const replacementKey = randomUUID();
    const replaced = await generate({ replace: true, expectedRevision: update.body.plan.generationRevision, requestKey: replacementKey });
    assert.equal(replaced.status, 200); assert.ok(replaced.body.plan.generated.remainingStudyMinutes > 0);
    assert.equal((await generate({ replace: true, expectedRevision: update.body.plan.generationRevision, requestKey: replacementKey })).body.plan.generationRevision, replaced.body.plan.generationRevision);
    assert.equal((await generate({ replace: true, expectedRevision: 0, requestKey: "stale" })).status, 409);
    const invalid = await asOwner(request(app).put(`/api/study-plan/plans/${id}`)).send({ ...daily, lessonIds: [], expectedRevision: replaced.body.plan.generationRevision }); assert.equal(invalid.status, 400);
    assert.equal((await StudyPlan.findById(id)).generated.remainingStudyMinutes, replaced.body.plan.generated.remainingStudyMinutes);
    // Legacy records have neither revision nor difficulty snapshots.
    const legacy = await StudyPlan.create({ ...daily, title: "قديم", owner: owner._id });
    await StudyPlan.collection.updateOne({ _id: legacy._id }, { $unset: { generationRevision: "" } });
    const old = await asOwner(request(app).post(`/api/study-plan/plans/${legacy._id}/generate`)).send({}); assert.equal(old.status, 200);
    assert.ok(old.body.plan.generated.lessons.every((l) => l.difficulty >= 1));
    const week = await asOwner(request(app).post("/api/study-plan/plans")).send({ ...daily, type: "weekly", availability: [], studyDays: ["2026-10-18", "2026-10-20"] });
    const weekId = week.body.plan._id;
    const wg = await asOwner(request(app).post(`/api/study-plan/plans/${weekId}/generate`)).send({}); assert.equal(wg.status, 200);
    assert.equal(wg.body.plan.generated.availableMinutes, null);
    const day = wg.body.plan.generated.days.find((d) => d.lessonIds.length);
    const linked = await asOwner(request(app).post("/api/study-plan/plans")).send({ ...daily, periodStart: day.date, availability: [{ date: day.date, start: "10:00", end: "11:00" }], lessonIds: day.lessonIds, parentWeeklyId: weekId });
    assert.equal(linked.status, 201);
    assert.equal((await asOwner(request(app).post(`/api/study-plan/plans/${linked.body.plan._id}/generate`)).send({})).status, 200);
    const conflict = await asOwner(request(app).put(`/api/study-plan/plans/${weekId}`)).send({ ...week.body.plan, studyDays: ["2026-10-21"], expectedRevision: wg.body.plan.generationRevision }); assert.equal(conflict.status, 409);
    const racePlan = await asOwner(request(app).post("/api/study-plan/plans")).send(daily);
    const race = await Promise.all([1, 2].map(() => asOwner(request(app).post(`/api/study-plan/plans/${racePlan.body.plan._id}/generate`)).send({ requestKey: "race" })));
    assert.ok(race.some((r) => r.status === 200)); assert.ok(race.every((r) => [200, 409].includes(r.status)));
    assert.equal((await StudyPlan.findById(racePlan.body.plan._id)).generationRevision, 1);
  } finally { if (User.db.readyState === 1) await clearTestCollections(); await disconnectTestDatabase(); }
});
